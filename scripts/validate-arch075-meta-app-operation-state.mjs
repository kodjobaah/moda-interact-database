import assert from 'node:assert/strict';
import { readFileSync, readdirSync } from 'node:fs';
const schema = readFileSync(new URL('../prisma/schema.prisma', import.meta.url), 'utf8');
const root = new URL('../prisma/migrations/', import.meta.url);
const target = readdirSync(root).find(name => name.endsWith('_arch075_meta_app_operation_state'));
assert.ok(target);
const sql = readFileSync(new URL(`${target}/migration.sql`, root), 'utf8');
const model = schema.match(/model MetaTemplateAppOperationState \{([\s\S]*?)\n\}/)?.[1];
assert.ok(model);
assert.match(model, /@@id\(\[environment, appId\]\)/);
assert.match(model, /environment\s+CommerceEnvironment/);
assert.match(model, /leaseGeneration\s+BigInt\s+@default\(0\)/);
assert.doesNotMatch(model, /@@index|shopId|wabaId|accessToken|Json|@relation/);
for (const reason of ['META_APP_OPERATION_IDENTITY_IMMUTABLE', 'META_APP_OPERATION_GENERATION_REGRESSION', 'META_APP_OPERATION_NEW_LEASE_GENERATION_REQUIRED', 'META_APP_OPERATION_LEASE_ACTIVE', 'META_APP_OPERATION_COOLDOWN_REGRESSION', 'META_APP_OPERATION_STATE_DELETE_FORBIDDEN']) assert.ok(sql.includes(reason));
assert.match(sql, /"consecutiveThrottleCount" BETWEEN 0 AND 31/);
assert.match(sql, /"appId" ~ '\^\[0-9\]\{1,32\}\$'/);
assert.doesNotMatch(sql, /DROP (?:TABLE|INDEX|TYPE)|RENAME/);
assert.equal((sql.match(/ALTER TABLE/g) ?? []).length, 1);
assert.match(sql, /ALTER TABLE "whatsapp"\."MetaTemplateAppOperationState"/);
console.log('PASS ARCH-075 app/environment identity, bounded invariant storage, fenced lease/cooldown guards, additive task-only migration');
